// Varied, encouraging specialist phrasing + evidence-based general tips.
// Selection is deterministic per (date, situation) so the text stays stable during a day
// and changes naturally from one day to the next.

export function seedPick(pool, seed, offset = 0) {
  if (!pool?.length) return null;
  const match=String(seed).match(/^(\d{4}-\d{2}-\d{2})(.*)$/);
  const day=match?Math.floor(Date.parse(match[1])/86400000):0;
  if(match)seed=match[2];
  let h = 2166136261;
  for (const ch of String(seed)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return pool[(Math.abs(h) + (Number.isFinite(day)?day:0) + offset) % pool.length];
}
export const say = (pool, seed, ctx) => { const t = seedPick(pool, seed); return typeof t === 'function' ? t(ctx) : t; };

