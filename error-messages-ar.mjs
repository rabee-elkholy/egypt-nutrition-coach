export function formatArabicError(code, params = {}, fallback = '') {
  const template = (code && ERROR_MESSAGES_AR[code]) || '';
  if (!template) return fallback || 'تعذر تنفيذ العملية؛ حاول مرة أخرى.';
  const fieldKey = params?.field;
  const fieldAr = (fieldKey && FIELD_LABELS_AR[fieldKey]) || fieldKey || 'القيمة';
  const merged = { ...params, fieldAr };
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) =>
    merged[k] !== undefined && merged[k] !== null ? String(merged[k]) : ''
  );
}
