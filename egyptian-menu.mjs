const tiers={low:1,medium:2,high:3};

function buildMenuList(list, prefix, regionList, lib) {
  return list.filter(m=>m[3].every(id=>MENU_PARTS[id]&&MENU_PARTS[id].items.every(i=>lib.ingredients[i.key])))
    .map(([id,name,slots,parts])=>({id:prefix+id,name,meal_slots:slots,regions:regionList,
      dish_family:slots[0]==='snack' ? (parts.some(p=>['yogurt','greekyogurt_part','greek_dates_pb','greek_honey_walnuts'].includes(p)) ? 'snack-yogurt' : (parts.some(p=>['almonds','peanuts','walnuts','cashews','peanutbutter_banana'].includes(p)) ? 'snack-nuts' : 'snack-fruit')) : family[parts.find(p=>MENU_PARTS[p].role==='main')],
      budget_tier:parts.map(p=>MENU_PARTS[p].budget).sort((a,b)=>tiers[b]-tiers[a])[0],
      items:parts.flatMap((p,index)=>MENU_PARTS[p].items.map(i=>({...i,component_id:'part-'+index}))),
      component_definitions:parts.map((p,index)=>({id:'part-'+index,name:MENU_PARTS[p].name,role:MENU_PARTS[p].role})),
      editorial_policy_version:MENU_VERSION,healthy_priority:true,
      notes:'حصة مقترحة محسوبة من المكونات المرجعية بالحالة والكمية الموضحتين. كمية الزيت محسوبة ضمن المكونات.'}));
}

export function egyptianMenus(lib) {
  return buildMenuList(menus, 'eg-menu-', ['egypt'], lib);
}

export function regionalMenus(lib, region = 'egypt') {
  if (region === 'egypt') return egyptianMenus(lib);
  const snacks = menus.filter(m => m[2][0] === 'snack');
  if (REGIONAL_MENU_DEFS[region]) {
    return buildMenuList([...REGIONAL_MENU_DEFS[region], ...snacks], `${region}-menu-`, [region], lib);
  }
  return [];
}
